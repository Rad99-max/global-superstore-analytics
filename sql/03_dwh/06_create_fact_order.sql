-- One order_id / customer_id pair, resolved through dim_customer.
CREATE TABLE IF NOT EXISTS dwh.fact_order (
    order_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id TEXT NOT NULL,
    customer_key BIGINT NOT NULL,
    geography_key BIGINT NOT NULL,
    order_date_key INTEGER NOT NULL,
    line_count BIGINT NOT NULL,
    total_quantity BIGINT,
    total_sales NUMERIC,
    total_profit NUMERIC,
    total_shipping_cost NUMERIC,
    _load_id UUID NOT NULL,
    _dq_flags TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    _dwh_loaded_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT fact_order_order_id_customer_key_key UNIQUE (order_id, customer_key),
    CONSTRAINT fact_order_customer_key_fkey
        FOREIGN KEY (customer_key) REFERENCES dwh.dim_customer (customer_key),
    CONSTRAINT fact_order_geography_key_fkey
        FOREIGN KEY (geography_key) REFERENCES dwh.dim_geography (geography_key),
    CONSTRAINT fact_order_order_date_key_fkey
        FOREIGN KEY (order_date_key) REFERENCES dwh.dim_date (date_key),
    CONSTRAINT fact_order_load_id_fkey
        FOREIGN KEY (_load_id) REFERENCES raw.load_log (load_id)
);

CREATE INDEX IF NOT EXISTS fact_order_customer_key_idx ON dwh.fact_order (customer_key);
CREATE INDEX IF NOT EXISTS fact_order_geography_key_idx ON dwh.fact_order (geography_key);
CREATE INDEX IF NOT EXISTS fact_order_order_date_key_idx ON dwh.fact_order (order_date_key);
CREATE INDEX IF NOT EXISTS fact_order_load_id_idx ON dwh.fact_order (_load_id);
