-- One Customer ID; names do not identify customers.
CREATE TABLE IF NOT EXISTS dwh.dim_customer (
    customer_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id TEXT NOT NULL,
    customer_name TEXT,
    segment TEXT,
    _dwh_loaded_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT dim_customer_customer_id_key UNIQUE (customer_id)
);
