-- One source order line; repeated products within an order are preserved.
CREATE TABLE IF NOT EXISTS dwh.fact_order_line (
    order_line_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_key BIGINT NOT NULL,
    customer_key BIGINT NOT NULL,
    product_key BIGINT NOT NULL,
    geography_key BIGINT NOT NULL,
    order_date_key INTEGER NOT NULL,
    ship_date_key INTEGER,
    row_id INTEGER,
    quantity INTEGER,
    sales NUMERIC,
    profit NUMERIC,
    shipping_cost NUMERIC,
    discount NUMERIC,
    discount_group TEXT NOT NULL,
    ship_mode TEXT,
    order_priority TEXT,
    city TEXT,
    state TEXT,
    postal_code TEXT,
    _raw_id BIGINT NOT NULL,
    _load_id UUID NOT NULL,
    _dq_flags TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    _dwh_loaded_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT fact_order_line_raw_id_key UNIQUE (_raw_id),
    CONSTRAINT fact_order_line_order_key_fkey
        FOREIGN KEY (order_key) REFERENCES dwh.fact_order (order_key),
    CONSTRAINT fact_order_line_customer_key_fkey
        FOREIGN KEY (customer_key) REFERENCES dwh.dim_customer (customer_key),
    CONSTRAINT fact_order_line_product_key_fkey
        FOREIGN KEY (product_key) REFERENCES dwh.dim_product (product_key),
    CONSTRAINT fact_order_line_geography_key_fkey
        FOREIGN KEY (geography_key) REFERENCES dwh.dim_geography (geography_key),
    CONSTRAINT fact_order_line_order_date_key_fkey
        FOREIGN KEY (order_date_key) REFERENCES dwh.dim_date (date_key),
    CONSTRAINT fact_order_line_ship_date_key_fkey
        FOREIGN KEY (ship_date_key) REFERENCES dwh.dim_date (date_key),
    CONSTRAINT fact_order_line_load_id_fkey
        FOREIGN KEY (_load_id) REFERENCES raw.load_log (load_id)
);

CREATE INDEX IF NOT EXISTS fact_order_line_order_key_idx ON dwh.fact_order_line (order_key);
CREATE INDEX IF NOT EXISTS fact_order_line_customer_key_idx ON dwh.fact_order_line (customer_key);
CREATE INDEX IF NOT EXISTS fact_order_line_product_key_idx ON dwh.fact_order_line (product_key);
CREATE INDEX IF NOT EXISTS fact_order_line_geography_key_idx ON dwh.fact_order_line (geography_key);
CREATE INDEX IF NOT EXISTS fact_order_line_order_date_key_idx ON dwh.fact_order_line (order_date_key);
CREATE INDEX IF NOT EXISTS fact_order_line_ship_date_key_idx ON dwh.fact_order_line (ship_date_key);
CREATE INDEX IF NOT EXISTS fact_order_line_load_id_idx ON dwh.fact_order_line (_load_id);
