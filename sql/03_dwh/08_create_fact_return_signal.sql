-- One source return signal; an unresolved order reference remains nullable.
CREATE TABLE IF NOT EXISTS dwh.fact_return_signal (
    return_signal_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_order_id TEXT,
    source_region TEXT,
    returned TEXT,
    order_key BIGINT,
    match_status TEXT NOT NULL,
    candidate_order_count BIGINT NOT NULL,
    _raw_id BIGINT NOT NULL,
    _load_id UUID NOT NULL,
    _dq_flags TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    _dwh_loaded_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT fact_return_signal_raw_id_key UNIQUE (_raw_id),
    CONSTRAINT fact_return_signal_order_key_fkey
        FOREIGN KEY (order_key) REFERENCES dwh.fact_order (order_key),
    CONSTRAINT fact_return_signal_load_id_fkey
        FOREIGN KEY (_load_id) REFERENCES raw.load_log (load_id)
);

CREATE INDEX IF NOT EXISTS fact_return_signal_order_key_idx ON dwh.fact_return_signal (order_key);
CREATE INDEX IF NOT EXISTS fact_return_signal_load_id_idx ON dwh.fact_return_signal (_load_id);
