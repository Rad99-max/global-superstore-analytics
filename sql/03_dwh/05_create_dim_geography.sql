-- One observed Market / Region / Country combination, not an address.
CREATE TABLE IF NOT EXISTS dwh.dim_geography (
    geography_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    market TEXT NOT NULL,
    region TEXT NOT NULL,
    country TEXT NOT NULL,
    _dwh_loaded_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT dim_geography_market_region_country_key UNIQUE (market, region, country)
);
