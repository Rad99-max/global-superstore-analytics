-- One calendar day; used for both Order Date and Ship Date roles.
CREATE TABLE IF NOT EXISTS dwh.dim_date (
    date_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calendar_date DATE NOT NULL,
    calendar_year SMALLINT NOT NULL,
    calendar_quarter SMALLINT NOT NULL,
    calendar_month SMALLINT NOT NULL,
    day_of_month SMALLINT NOT NULL,
    iso_day_of_week SMALLINT NOT NULL,
    iso_week SMALLINT NOT NULL,
    iso_year SMALLINT NOT NULL,
    _dwh_loaded_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT dim_date_calendar_date_key UNIQUE (calendar_date)
);
