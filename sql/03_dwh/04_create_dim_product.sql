-- One Product ID; profitability is calculated from facts.
CREATE TABLE IF NOT EXISTS dwh.dim_product (
    product_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id TEXT NOT NULL,
    product_name TEXT,
    category TEXT,
    sub_category TEXT,
    _dwh_loaded_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT dim_product_product_id_key UNIQUE (product_id)
);
