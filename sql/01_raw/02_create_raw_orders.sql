-- Source column names and values are preserved; business fields are nullable.
CREATE TABLE IF NOT EXISTS raw.orders (
    "Row ID" INTEGER,
    "Order ID" TEXT,
    "Order Date" DATE,
    "Ship Date" DATE,
    "Ship Mode" TEXT,
    "Customer ID" TEXT,
    "Customer Name" TEXT,
    "Segment" TEXT,
    "Postal Code" TEXT,
    "City" TEXT,
    "State" TEXT,
    "Country" TEXT,
    "Region" TEXT,
    "Market" TEXT,
    "Product ID" TEXT,
    "Category" TEXT,
    "Sub-Category" TEXT,
    "Product Name" TEXT,
    "Sales" DOUBLE PRECISION,
    "Quantity" INTEGER,
    "Discount" DOUBLE PRECISION,
    "Profit" DOUBLE PRECISION,
    "Shipping Cost" DOUBLE PRECISION,
    "Order Priority" TEXT,

    -- Technical lineage fields.
    _raw_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    _loaded_at TIMESTAMPTZ NOT NULL,
    _source_file TEXT NOT NULL,
    _source_sheet TEXT NOT NULL,
    _source_row_number INTEGER NOT NULL,
    _load_id UUID NOT NULL,

    CONSTRAINT orders_load_id_fkey
        FOREIGN KEY (_load_id) REFERENCES raw.load_log (load_id)
);

CREATE INDEX IF NOT EXISTS orders_load_id_idx ON raw.orders (_load_id);
